-- Ordem do script:
--   1. Limpeza  - apaga as tabelas de execuções anteriores (se existirem)
--   2. CREATE   - 8 tabelas com PK, FK, NOT NULL, UNIQUE e CHECK
--   3. INSERT   - carga inicial da loja de demonstração
--
-- Convenções:
--   - Prefixo LCP_ em todas as tabelas (evita conflito com palavras reservadas)
--   - PKs numéricas com IDENTITY começando em 1000; a carga inicial usa ids
--     fixos abaixo de 1000, então os cadastros feitos pelo Java nunca colidem
--   - Booleanos como NUMBER(1) com CHECK (0 = não, 1 = sim)
--   - Relacionamento N:N: LCP_LISTA_COMPRA <-> LCP_PRODUTO pela tabela
--     associativa LCP_ITEM_LISTA (com quantidade e flag de coletado)
--
-- Como rodar: no SQL Developer, abra este arquivo e use "Executar Script" (F5).
-- ============================================================================


-- ============================================================================
-- 1. LIMPEZA - remove só as tabelas que já existem, então roda sem erro
--    tanto na primeira execução quanto nas seguintes
-- ============================================================================

-- [INICIO-LIMPEZA]
BEGIN
    FOR t IN (SELECT table_name
                FROM user_tables
               WHERE table_name IN ('LCP_CHAMADO_RUPTURA', 'LCP_ITEM_LISTA',
                                    'LCP_LISTA_COMPRA', 'LCP_VENDEDOR',
                                    'LCP_CLIENTE', 'LCP_PRODUTO',
                                    'LCP_CORREDOR', 'LCP_SETOR'))
    LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
    END LOOP;
END;
/
-- [FIM-LIMPEZA]


-- ============================================================================
-- 2. CREATE
-- ============================================================================

-- Setor da loja (ex.: Construção & Hidráulica). Um setor tem vários corredores.
CREATE TABLE LCP_SETOR (
    id_setor    NUMBER(10)        GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    codigo      VARCHAR2(20 CHAR) NOT NULL,
    nome        VARCHAR2(60 CHAR) NOT NULL,
    CONSTRAINT pk_lcp_setor        PRIMARY KEY (id_setor),
    CONSTRAINT uk_lcp_setor_codigo UNIQUE (codigo)
);

-- Corredor com a posição no mapa da loja (a mesma geometria usada no front
-- e no cálculo de distância do Java). Cada placa QR aponta para um corredor.
CREATE TABLE LCP_CORREDOR (
    id_corredor NUMBER(10)       GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    codigo      VARCHAR2(5 CHAR) NOT NULL,
    id_setor    NUMBER(10)       NOT NULL,
    pos_x       NUMBER(5)        NOT NULL,
    pos_y       NUMBER(5)        NOT NULL,
    largura     NUMBER(5)        NOT NULL,
    altura      NUMBER(5)        NOT NULL,
    CONSTRAINT pk_lcp_corredor        PRIMARY KEY (id_corredor),
    CONSTRAINT uk_lcp_corredor_codigo UNIQUE (codigo),
    CONSTRAINT fk_lcp_corredor_setor  FOREIGN KEY (id_setor) REFERENCES LCP_SETOR (id_setor),
    CONSTRAINT ck_lcp_corredor_dim    CHECK (largura > 0 AND altura > 0 AND pos_x >= 0 AND pos_y >= 0)
);

-- Produto exposto em um corredor. Estoque 0 = ruptura de gôndola.
CREATE TABLE LCP_PRODUTO (
    id_produto     NUMBER(10)         GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    sku            VARCHAR2(20 CHAR)  NOT NULL,
    nome           VARCHAR2(120 CHAR) NOT NULL,
    marca          VARCHAR2(60 CHAR),
    categoria      VARCHAR2(30 CHAR)  NOT NULL,
    preco          NUMBER(10,2)       NOT NULL,
    estoque        NUMBER(6)          NOT NULL,
    id_corredor    NUMBER(10)         NOT NULL,
    modulo_gondola VARCHAR2(40 CHAR),
    prateleira     VARCHAR2(60 CHAR),
    ordem_corredor NUMBER(4)          NOT NULL,
    CONSTRAINT pk_lcp_produto          PRIMARY KEY (id_produto),
    CONSTRAINT uk_lcp_produto_sku      UNIQUE (sku),
    CONSTRAINT fk_lcp_produto_corredor FOREIGN KEY (id_corredor) REFERENCES LCP_CORREDOR (id_corredor),
    CONSTRAINT ck_lcp_produto_categoria CHECK (categoria IN ('MATERIAIS_CONSTRUCAO', 'HIDRAULICA',
                                                             'ELETRICA', 'TINTAS_ACESSORIOS', 'FERRAMENTAS')),
    CONSTRAINT ck_lcp_produto_preco    CHECK (preco >= 0),
    CONSTRAINT ck_lcp_produto_estoque  CHECK (estoque >= 0)
);

-- Cliente que usa o Modo Missão no celular.
CREATE TABLE LCP_CLIENTE (
    id_cliente     NUMBER(10)         GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    nome           VARCHAR2(100 CHAR) NOT NULL,
    email          VARCHAR2(120 CHAR) NOT NULL,
    telefone       VARCHAR2(20 CHAR),
    perfil_projeto VARCHAR2(30 CHAR)  NOT NULL,
    CONSTRAINT pk_lcp_cliente        PRIMARY KEY (id_cliente),
    CONSTRAINT uk_lcp_cliente_email  UNIQUE (email),
    CONSTRAINT ck_lcp_cliente_perfil CHECK (perfil_projeto IN ('REFORMA_BANHEIRO', 'PINTURA_COMPLETA',
                                                               'INSTALACAO_ELETRICA', 'OUTRO'))
);

-- Vendedor (assessor) que recebe os chamados no Modo Consultor.
CREATE TABLE LCP_VENDEDOR (
    id_vendedor       NUMBER(10)         GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    matricula         VARCHAR2(10 CHAR)  NOT NULL,
    nome              VARCHAR2(100 CHAR) NOT NULL,
    telefone          VARCHAR2(20 CHAR),
    especialidade     VARCHAR2(30 CHAR)  NOT NULL,
    id_corredor_atual NUMBER(10),
    disponivel        NUMBER(1)          DEFAULT 1 NOT NULL,
    CONSTRAINT pk_lcp_vendedor           PRIMARY KEY (id_vendedor),
    CONSTRAINT uk_lcp_vendedor_matricula UNIQUE (matricula),
    CONSTRAINT fk_lcp_vendedor_corredor  FOREIGN KEY (id_corredor_atual) REFERENCES LCP_CORREDOR (id_corredor),
    CONSTRAINT ck_lcp_vendedor_especial  CHECK (especialidade IN ('MATERIAIS_CONSTRUCAO', 'HIDRAULICA',
                                                                  'ELETRICA', 'TINTAS_ACESSORIOS', 'FERRAMENTAS')),
    CONSTRAINT ck_lcp_vendedor_disp      CHECK (disponivel IN (0, 1))
);

-- Lista de compras (a "missão") de um cliente. Apagar o cliente apaga as listas.
CREATE TABLE LCP_LISTA_COMPRA (
    id_lista     NUMBER(10)        GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    id_cliente   NUMBER(10)        NOT NULL,
    nome         VARCHAR2(80 CHAR) NOT NULL,
    data_criacao TIMESTAMP         DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_lcp_lista_compra PRIMARY KEY (id_lista),
    CONSTRAINT fk_lcp_lista_cliente FOREIGN KEY (id_cliente) REFERENCES LCP_CLIENTE (id_cliente)
        ON DELETE CASCADE
);

-- Tabela associativa do N:N entre LISTA_COMPRA e PRODUTO.
-- Uma lista tem vários produtos e um produto aparece em várias listas.
CREATE TABLE LCP_ITEM_LISTA (
    id_lista   NUMBER(10) NOT NULL,
    id_produto NUMBER(10) NOT NULL,
    quantidade NUMBER(4)  NOT NULL,
    coletado   NUMBER(1)  DEFAULT 0 NOT NULL,
    CONSTRAINT pk_lcp_item_lista      PRIMARY KEY (id_lista, id_produto),
    CONSTRAINT fk_lcp_item_lista      FOREIGN KEY (id_lista)   REFERENCES LCP_LISTA_COMPRA (id_lista)
        ON DELETE CASCADE,
    CONSTRAINT fk_lcp_item_produto    FOREIGN KEY (id_produto) REFERENCES LCP_PRODUTO (id_produto),
    CONSTRAINT ck_lcp_item_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_lcp_item_coletado   CHECK (coletado IN (0, 1))
);

-- Chamado aberto pelo botão "Não achei": liga cliente, produto e o vendedor
-- escolhido para atender.
CREATE TABLE LCP_CHAMADO_RUPTURA (
    id_chamado      NUMBER(10)         GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    id_cliente      NUMBER(10)         NOT NULL,
    id_produto      NUMBER(10)         NOT NULL,
    id_vendedor     NUMBER(10),
    status          VARCHAR2(30 CHAR)  NOT NULL,
    prioridade      VARCHAR2(30 CHAR)  NOT NULL,
    observacao      VARCHAR2(400 CHAR),
    data_abertura   TIMESTAMP          DEFAULT CURRENT_TIMESTAMP NOT NULL,
    data_fechamento TIMESTAMP,
    CONSTRAINT pk_lcp_chamado          PRIMARY KEY (id_chamado),
    CONSTRAINT fk_lcp_chamado_cliente  FOREIGN KEY (id_cliente)  REFERENCES LCP_CLIENTE (id_cliente),
    CONSTRAINT fk_lcp_chamado_produto  FOREIGN KEY (id_produto)  REFERENCES LCP_PRODUTO (id_produto),
    CONSTRAINT fk_lcp_chamado_vendedor FOREIGN KEY (id_vendedor) REFERENCES LCP_VENDEDOR (id_vendedor),
    CONSTRAINT ck_lcp_chamado_status   CHECK (status IN ('AGUARDANDO_FILA', 'EM_DESLOCAMENTO', 'EM_ATENDIMENTO',
                                                         'SUBSTITUTO_OFERECIDO', 'CONCLUIDO_PRODUTO_ENCONTRADO',
                                                         'CONCLUIDO_COM_SUBSTITUTO', 'RUPTURA_CONFIRMADA',
                                                         'CANCELADO_PELO_CLIENTE')),
    CONSTRAINT ck_lcp_chamado_prior    CHECK (prioridade IN ('ALTA_PROJETO_PARADO', 'MEDIA', 'BAIXA')),
    CONSTRAINT ck_lcp_chamado_datas    CHECK (data_fechamento IS NULL OR data_fechamento >= data_abertura)
);


